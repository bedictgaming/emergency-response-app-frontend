export function MacbookScroll({ src, title, badge }: { src: string; title?: React.ReactNode; badge?: React.ReactNode }) {
 const ref = useRef<HTMLDivElement>(null);
 const active = useMotionActivity(ref);
 const { scrollYProgress } = useScroll({ target: ref, offset: ["start end", "end center"] });
 const scaleX = useTransform(scrollYProgress, [0, 0.7, 1], [1, 1.12, 1.12]);
 const scaleY = useTransform(scrollYProgress, [0, 0.7, 1], [0.78, 1, 1]);
 const translate = useTransform(scrollYProgress, [0, 0.7, 1], [0, -20, -20]);
 const rotate = useTransform(scrollYProgress, [0, 0.7, 1], [-28, 0, 0]);
 return <div ref={ref} data-macbook-preview className={styles.preview}>
   {title}
   <div className={styles.stage}>
     <div className={styles.device}>
       <Lid src={src} scaleX={active ? scaleX : undefined} scaleY={active ? scaleY : undefined}
         rotate={active ? rotate : undefined} translate={active ? translate : undefined} />
       <div data-macbook-base className={styles.base} aria-hidden="true">
         <div className="relative h-8 w-full"><div className="absolute inset-x-0 mx-auto h-3 w-[80%] bg-[#050505]" /></div>
         <div className="relative flex"><div className="w-[10%]"><SpeakerGrid /></div><div className="w-[80%]"><Keypad /></div><div className="w-[10%]"><SpeakerGrid /></div></div>
         <Trackpad />
         {badge && <div className="absolute bottom-4 left-4">{badge}</div>}
       </div>
     </div>
   </div>
 </div>;
}
export const Lid = ({
  scaleX,
  scaleY,
  rotate,
  translate,
  src,
}: {
  scaleX: MotionValue<number> | undefined;
  scaleY: MotionValue<number> | undefined;
  rotate: MotionValue<number> | undefined;
  translate: MotionValue<number> | undefined;
  src?: string;
}) => {
  return (
    <div className="relative [perspective:800px]">
      <div className="relative h-80 w-[32rem]" aria-hidden="true" />
      <motion.div
        style={{
          scaleX: scaleX,
          scaleY: scaleY,
          rotateX: rotate,
          translateY: translate,
          // One flat screen plane; nested 3D compositing can drop image tiles on phones.
          transformStyle: "flat",
          transformOrigin: "top",
        }}
        className="absolute inset-0 h-80 w-[32rem] rounded-2xl bg-[#010101] p-2"
      >
        <div className="absolute inset-0 rounded-lg bg-[#272729]" />
        <img
          src={src as string}
          alt="Citizen dashboard preview with synthetic demonstration data" width={1440} height={900} loading="lazy" decoding="async"
          className="absolute inset-0 h-full w-full rounded-lg object-cover object-left-top"
        />
      </motion.div>
    </div>
  );
};

